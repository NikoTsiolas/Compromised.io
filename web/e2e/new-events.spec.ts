// The "N new events" bar: a new event reaching the database while a reader has the page open is
// announced by the bar after the next 60-second poll, and appears only when the bar is pressed.
// This file adds events to the shared test database, so playwright.config.ts runs it in its own
// project after every read-only test. The added item is synthetic and says so in its headline.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

import { offline, expect, test } from "./test";

import { databaseUrl } from "./env";

offline();

// The real event that leads the All tab: named, covered by three outlets, with a picture.
const NEWEST_REAL =
  "1Password customer data stolen after employee GitHub account breach";
// Names a catalogued product and an attack, so the scope rules put it on the All tab.
const SYNTHETIC_HEADLINE =
  "[Synthetic test item] Windows zero-day exploited in attacks while the page is open";

function syntheticFeed(id: string, publishedAt: Date): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- SYNTHETIC TEST DATA, generated by web/e2e/new-events.spec.ts. Not a real incident. -->
<rss version="2.0"><channel>
  <title>Synthetic test feed</title><link>https://example.com/</link>
  <description>Synthetic test data</description>
  <item>
    <title>${SYNTHETIC_HEADLINE}</title>
    <link>https://example.com/synthetic-newer-event/${id}</link>
    <guid>https://example.com/synthetic-newer-event/${id}</guid>
    <pubDate>${publishedAt.toUTCString()}</pubDate>
    <description>Synthetic excerpt.</description>
  </item>
</channel></rss>`;
}

function ingestSyntheticEvent(file: string) {
  execFileSync(
    "uv",
    ["run", "python", "-m", "compromised.seed", `bleepingcomputer=${file}`],
    {
      cwd: path.resolve(__dirname, "../../api"),
      env: { ...process.env, DATABASE_URL: databaseUrl, ENVIRONMENT: "test" },
      stdio: "pipe",
    },
  );
}

test("new events wait behind the bar until the reader asks for them", async ({
  page,
}, testInfo) => {
  await page.clock.install();
  await page.goto("/");
  // Hydrated (the widget rail marks itself ready), so the 60-second poll is running.
  await expect(page.getByRole("complementary", { name: "Widgets" })).toHaveAttribute(
    "data-ready",
    "true",
  );

  const rows = page.getByRole("article");
  const topHeading = rows.first().getByRole("heading");
  const before = await topHeading.textContent();
  expect(before).toBeTruthy();
  const bar = page.getByRole("button", { name: /^\d+ new events? Show$/ });
  await expect(bar).toHaveCount(0);
  const topBefore = (await rows.first().boundingBox())!.y;

  const file = testInfo.outputPath("newer-event.xml");
  writeFileSync(file, syntheticFeed(`${Date.now()}`, new Date()));
  ingestSyntheticEvent(file);

  // Nothing changes before the next poll, and the poll only announces.
  await page.clock.runFor(60_000);
  await expect(bar).toBeVisible();
  await expect(bar).toHaveAccessibleName("1 new event Show");
  await expect(topHeading).toHaveText(before!);
  expect((await rows.first().boundingBox())!.y).toBe(topBefore);

  await bar.click();
  // The arrival has no picture, so the pictured 1Password story (under 24 hours older) keeps
  // the lead and the arrival becomes the first card (lib/featured.ts).
  const cards = page.getByRole("list", { name: "More top stories" }).getByRole("heading");
  await expect(cards.first()).toHaveText(SYNTHETIC_HEADLINE);
  await expect(topHeading).toHaveText(before!);
  // The newly arrived story fades in; stories that were already on the page and only moved
  // along do not.
  await expect(cards.first().locator("[data-fade-word]").first()).toBeVisible();
  await expect(cards.nth(1).locator("[data-fade-word]")).toHaveCount(0);
  await expect(
    page.getByRole("region", { name: "All events" }).locator("[data-fade-word]"),
  ).toHaveCount(0);
  await expect(bar).toHaveCount(0);
  await expect(page.getByRole("heading", { name: NEWEST_REAL })).toBeVisible();
});
