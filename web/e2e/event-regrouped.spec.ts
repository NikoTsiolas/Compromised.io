// Browser seam: an event page's address survives regrouping (#11). Correcting a grouping mistake
// (deduplicator.move_record) can delete an event whose last record moved elsewhere; its old
// address must then lead to the event that record joined. This file writes to the shared test
// database, so playwright.config.ts runs it after every read-only test. Both items are synthetic
// and say so in their headlines.
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { offline, expect, test } from "./test";

import { databaseUrl } from "./env";

offline();

const MOVED = "[Synthetic test item] Regrouping check: the story that moves";
const KEPT = "[Synthetic test item] Regrouping check: the story it joins";

const feed = `<?xml version="1.0" encoding="utf-8"?>
<!-- SYNTHETIC TEST DATA, generated by web/e2e/event-regrouped.spec.ts. Not a real incident. -->
<rss version="2.0"><channel>
  <title>Synthetic test feed</title><link>https://example.com/</link>
  <description>Synthetic test data</description>
  <item>
    <title>${MOVED}</title>
    <link>https://example.com/synthetic-regrouping/moved</link>
    <pubDate>Mon, 02 Nov 2026 08:00:00 GMT</pubDate>
    <description>Synthetic excerpt.</description>
  </item>
  <item>
    <title>${KEPT}</title>
    <link>https://example.com/synthetic-regrouping/kept</link>
    <pubDate>Mon, 02 Nov 2026 07:00:00 GMT</pubDate>
    <description>Synthetic excerpt.</description>
  </item>
</channel></rss>`;

// Ingests both items, then moves MOVED's record into KEPT's event, as a maintainer correcting a
// grouping would, and prints "<deleted event id> <joined event id>".
const regroup = `
import sys, psycopg
from compromised.pipeline import deduplicator
moved, kept = sys.argv[1:3]
with psycopg.connect(sys.argv[3], autocommit=True) as conn:
    record_id, old = conn.execute(
        "select id, event_id from source_records where headline = %s", (moved,)).fetchone()
    [new] = conn.execute("select event_id from source_records where headline = %s", (kept,)).fetchone()
    deduplicator.move_record(conn, record_id, new)
    print(old, new)
`;

function api(args: string[]) {
  return execFileSync("uv", ["run", ...args], {
    cwd: path.resolve(__dirname, "../../api"),
    env: { ...process.env, DATABASE_URL: databaseUrl, ENVIRONMENT: "test" },
    encoding: "utf8",
  });
}

test("an event emptied by regrouping redirects to the event its story joined", async ({
  page,
}) => {
  const file = path.join(mkdtempSync(path.join(tmpdir(), "regroup-")), "feed.xml");
  writeFileSync(file, feed);
  api(["python", "-m", "compromised.seed", `securityweek=${file}`]);
  const [oldId, newId] = api(["python", "-c", regroup, MOVED, KEPT, databaseUrl])
    .trim()
    .split(" ");
  expect(oldId).not.toBe(newId);

  const response = await page.goto(`/events/${oldId}`);

  expect(response?.request().redirectedFrom()?.url()).toMatch(new RegExp(`/events/${oldId}$`));
  await expect(page).toHaveURL(new RegExp(`/events/${newId}$`));
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(KEPT);
  await expect(page.getByRole("list", { name: "Timeline" }).getByRole("link")).toHaveText([
    KEPT,
    MOVED,
  ]);
});
