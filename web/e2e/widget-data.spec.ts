// Browser seam for the widgets' real figures (#15): the homepage reads them from the API. This
// file loads a SYNTHETIC KEV catalog and a SYNTHETIC breach into the shared test database, so
// playwright.config.ts runs it after every other spec. Every entry is dated relative to today,
// so the 12-month window always holds them, and the catalog entries are all older than the
// KEV adapter's 30-day backfill, so none becomes a feed event. CVE numbers use the impossible
// year 0000; names start with "[Synthetic test entry]".
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";

import { offline, expect, test, type Page } from "./test";

import { databaseUrl } from "./env";

offline();
// One seeding for the whole file: in parallel, every worker would run beforeAll and add its own
// copy of the breach.
test.describe.configure({ mode: "serial" });

const rail = (page: Page) => page.getByRole("complementary", { name: "Widgets" });

/** The 10th (or given day) of the month `monthsAgo` months before this one, "YYYY-MM-DD". */
function dayIn(monthsAgo: number, day: number): string {
  const now = new Date();
  return new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() - monthsAgo, day))
    .toISOString()
    .slice(0, 10);
}

const longMonth = (isoDate: string) =>
  new Date(`${isoDate}T00:00:00Z`).toLocaleDateString("en-GB", {
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  });

// [months ago, day, CVE, vendor, product, weakness, ransomware]
const ENTRIES: [number, number, string, string, string, string, string][] = [
  [2, 10, "CVE-0000-0201", "Mozilla", "Firefox", "Use-After-Free Vulnerability", "Unknown"],
  [4, 20, "CVE-0000-0401", "Microsoft", "Windows", "Use-After-Free Vulnerability", "Known"],
  [4, 18, "CVE-0000-0402", "Fortinet", "FortiOS", "Heap Overflow Vulnerability", "Known"],
  [4, 14, "CVE-0000-0403", "Danfoss", "AK-SM 800A Series", "Missing Authorization", "Unknown"],
  [4, 12, "CVE-0000-0404", "Apple", "iOS", "Memory Corruption Vulnerability", "Unknown"],
  [4, 5, "CVE-0000-0405", "Google", "Chromium V8", "Type Confusion Vulnerability", "Unknown"],
  [4, 2, "CVE-0000-0406", "Ivanti", "Connect Secure", "Code Injection Vulnerability", "Unknown"],
  [6, 10, "CVE-0000-0601", "Danfoss", "AK-SM 800A Series", "Improper Authentication", "Unknown"],
  [8, 10, "CVE-0000-0801", "Ivanti", "Connect Secure", "Authentication Bypass", "Known"],
  [10, 10, "CVE-0000-1001", "Cisco", "IOS XE", "Privilege Escalation Vulnerability", "Unknown"],
  [10, 11, "CVE-0000-1002", "Cisco", "IOS XE", "Command Injection Vulnerability", "Unknown"],
];

function syntheticCatalog(): string {
  const vulnerabilities = ENTRIES.map(([ago, day, cve, vendor, product, weakness, ransomware]) => ({
    cveID: cve,
    vendorProject: vendor,
    product,
    vulnerabilityName: `[Synthetic test entry] ${vendor} ${product} ${weakness}`,
    dateAdded: dayIn(ago, day),
    shortDescription: "Synthetic test entry. Not a real vulnerability.",
    requiredAction: "Synthetic test entry: no action.",
    dueDate: dayIn(ago, day),
    knownRansomwareCampaignUse: ransomware,
  }));
  return JSON.stringify({
    _comment: "SYNTHETIC TEST DATA generated by web/e2e/widget-data.spec.ts. Not real.",
    catalogVersion: "0000.00.00",
    count: vulnerabilities.length,
    vulnerabilities,
  });
}

const BREACH =
  "[Synthetic test item] Contoso Pharmacy data breach exposes customer prescriptions";

function syntheticBreach(id: string): string {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- SYNTHETIC TEST DATA, generated by web/e2e/widget-data.spec.ts. Not a real incident. -->
<rss version="2.0"><channel>
  <title>Synthetic test feed</title><link>https://example.com/</link>
  <description>Synthetic test data</description>
  <item>
    <title>${BREACH}</title>
    <link>https://example.com/synthetic-widget-data/${id}</link>
    <guid>https://example.com/synthetic-widget-data/${id}</guid>
    <category>Contoso Pharmacy</category>
    <pubDate>${new Date().toUTCString()}</pubDate>
    <description>Synthetic excerpt.</description>
  </item>
</channel></rss>`;
}

function seed(...samples: string[]) {
  execFileSync("uv", ["run", "python", "-m", "compromised.seed", ...samples], {
    cwd: path.resolve(__dirname, "../../api"),
    env: { ...process.env, DATABASE_URL: databaseUrl, ENVIRONMENT: "test" },
    stdio: "pipe",
  });
}

test.beforeAll(({}, testInfo) => {
  const catalog = testInfo.outputPath("kev-catalog.json");
  const breach = testInfo.outputPath("breach.xml");
  writeFileSync(catalog, syntheticCatalog());
  writeFileSync(breach, syntheticBreach(`${Date.now()}`));
  seed(`cisa-kev=${catalog}`, `bleepingcomputer=${breach}`);
});

test("the chart shows twelve real months with the API's spike month and its notable flaws", async ({
  page,
}) => {
  await page.goto("/");

  const chart = rail(page).getByRole("region", { name: "Exploited flaws by month" });
  await expect(chart.locator("[data-month]")).toHaveCount(12);
  await expect(chart).toContainText("11 in 12 months");
  // 6 in one month against 1, 1, 1 and 2 elsewhere: the only month one deviation above average.
  const spikes = chart.locator("[data-month][data-spike]");
  await expect(spikes).toHaveCount(1);
  const spikeMonth = longMonth(dayIn(4, 1));
  await expect(spikes).toHaveAttribute("data-month", spikeMonth);
  await expect(spikes).toContainText("6");

  await chart
    .getByRole("button", { name: `${spikeMonth}: 6 exploited flaws, a spike month` })
    .focus();
  const tip = chart.getByRole("tooltip");
  await expect(tip).toContainText("Notable");
  // Newest three of the flaws in products people use or known to be used by ransomware.
  await expect(tip.getByRole("listitem")).toHaveText([
    "Windows: [Synthetic test entry] Microsoft Windows Use-After-Free Vulnerability",
    "FortiOS: [Synthetic test entry] Fortinet FortiOS Heap Overflow Vulnerability",
    "iOS: [Synthetic test entry] Apple iOS Memory Corruption Vulnerability",
  ]);
});

test("recently exploited lists the newest flaws in products people use, by day", async ({
  page,
}) => {
  await page.goto("/");

  const list = rail(page).getByRole("region", { name: "Recently exploited" }).getByRole("listitem");
  await expect(list).toHaveCount(4);
  await expect(list.first()).toContainText("Firefox");
  await expect(list.first()).toContainText("CVE-0000-0201");
  await expect(list.first().locator("time")).toHaveAttribute("datetime", dayIn(2, 10));
  await expect(list.nth(1)).toContainText("Windows");
  await expect(list.nth(2)).toContainText("iOS");
  await expect(list.nth(3)).toContainText("Chrome");
});

